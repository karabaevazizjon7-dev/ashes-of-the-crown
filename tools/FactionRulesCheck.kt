package com.ashes.crown

fun main() {
    check(FactionManager.normalize(-101) == -100)
    check(FactionManager.normalize(101) == 100)
    check(FactionManager.applyDelta(99, 10) == 100)
    check(FactionManager.applyDelta(-99, -10) == -100)
    check(FactionManager.applyDelta(0, Int.MAX_VALUE) == 100)
    check(FactionManager.applyDelta(0, Int.MIN_VALUE) == -100)
    check(FactionManager.rank("crown", -50) == "Подозрение")
    check(FactionManager.rank("merchants", 0) == "Деловой нейтралитет")
    check(FactionManager.rank("people", 20) == "Народная поддержка")
    check(FactionManager.rank("rose", 60) == "Доверенное лицо")
    check(FactionManager.rank("unknown", 100) == "Неизвестная фракция")
    val snapshot = FactionManager.snapshot(120, -120, 35, 80)
    check(snapshot.standings.size == 4)
    check(snapshot.standing("crown")?.score == 100)
    check(snapshot.standing("merchants")?.score == -100)
    check(snapshot.standing("people")?.rank == "Народная поддержка")
    check(snapshot.standing("rose")?.rank == "Доверенное лицо")
    check(snapshot.standing("unknown") == null)
    val balanced = FactionAgendaManager.evaluate(0, 0, 20, 0)
    check(balanced.isEmpty())
    val divided = FactionAgendaManager.evaluate(70, 65, -55, 75)
    check(divided.any { it.id == "crown_rose_conflict" && it.urgency == 3 })
    check(divided.any { it.id == "people_relief" })
    check(divided.any { it.id == "wealth_people_gap" })
    check(divided.zipWithNext().all { (a, b) -> a.urgency >= b.urgency })
    val clamped = FactionAgendaManager.evaluate(Int.MAX_VALUE, 0, Int.MIN_VALUE, 0)
    check(clamped.any { it.id == "people_relief" })
    println("Faction reputation bounds, delta overflow protection, rank thresholds, snapshots and political agenda conditions passed")
}
